//! Epicenter Tauri build script.

use std::env;
use std::fs;
use std::path::Path;

include!("src/command_names.rs");

fn main() {
    println!("cargo:rerun-if-env-changed=EPICENTER_SERVER_ORIGIN");
    epicenter_transcription_build::link_runtime();

    remove_parked_permissions();
    let manifest = tauri_build::AppManifest::new().commands(registered_commands());
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(manifest))
        .expect("failed to build Epicenter's Tauri manifest");
}

/// The commands this build registers, which are the ones the Tauri manifest
/// declares: the page API, the sign-in's, and the dictation commands only
/// with the `dictation` feature.
fn registered_commands() -> &'static [&'static str] {
    let mut commands = [COMMANDS, ACCOUNT_COMMANDS].concat();
    if env::var_os("CARGO_FEATURE_DICTATION").is_some() {
        commands.extend_from_slice(DICTATION_COMMANDS);
    }
    Box::leak(commands.into_boxed_slice())
}

/// Remove the permission files a `dictation` build generated, so a default
/// build defines none of those permissions: tauri-build regenerates only the
/// files for declared commands, then defines one for every file in the
/// directory.
fn remove_parked_permissions() {
    if env::var_os("CARGO_FEATURE_DICTATION").is_some() {
        return;
    }
    for command in DICTATION_COMMANDS {
        let file = Path::new("permissions/autogenerated").join(format!("{command}.toml"));
        if let Err(error) = fs::remove_file(&file) {
            assert!(
                error.kind() == std::io::ErrorKind::NotFound,
                "remove {}: {error}",
                file.display()
            );
        }
    }
}
