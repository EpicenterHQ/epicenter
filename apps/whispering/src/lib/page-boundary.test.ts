/**
 * What the page may import.
 *
 * The page runs in a WebView and in a browser tab, so nothing under `src/` may
 * reach Node or Bun, or the directory opener that runs there. It names the
 * folder contract through `@epicenter/folder`. A folder is opened in exactly
 * two places, each naming its entry: the browser workspace opens browser
 * storage, and the desktop workspace opens the directory the desktop shell
 * grants.
 * The build picks the workspace (`#platform/workspace`), so no page code asks
 * where it is running. The recording workflow is
 * file-backed, so it may not reach the Yjs store either. This reads the
 * sources, so a violation names its file.
 *
 * The same reading establishes who owns the folder: the app layout opens one
 * session, and pages only receive it.
 */
import { expect, test } from 'bun:test';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = fileURLToPath(new URL('..', import.meta.url));

/** Epicenter's typed command bindings, generated by its build; only the desktop workspace imports them. */
const GENERATED = 'lib/tauri/bindings.gen.ts';

/** Every page source under `directory`, in name order on every filesystem. */
function* sources(directory: string): Generator<string> {
	for (const name of readdirSync(directory).sort()) {
		const path = join(directory, name);
		if (statSync(path).isDirectory()) yield* sources(path);
		else if (
			/\.(ts|svelte)$/.test(name) &&
			!/\.test(-support)?\.ts$/.test(name)
		)
			yield path;
	}
}

const IMPORT = /(?:from\s+|import\s*\(\s*|import\s+)['"]([^'"]+)['"]/g;

const files = [...sources(src)]
	.map((path) => ({
		path: relative(src, path),
		text: readFileSync(path, 'utf8'),
	}))
	.filter((file) => file.path !== GENERATED);

function importers(matches: (specifier: string) => boolean) {
	const found: string[] = [];
	for (const file of files)
		for (const [, specifier] of file.text.matchAll(IMPORT))
			if (specifier !== undefined && matches(specifier))
				found.push(`${file.path} imports ${specifier}`);
	return found;
}

test('the page imports no Node or Bun module, and Tauri only for a response’s Channel and the opener', () => {
	expect(
		importers(
			(specifier) =>
				specifier.startsWith('node:') ||
				specifier.startsWith('bun') ||
				// The directory opener runs in Bun, never in a page.
				specifier === '@epicenter/folder/bun',
		),
	).toEqual([]);
	// The Tauri APIs the page names: the desktop connections open the
	// `Channel` an AI response streams back on, and the desktop microphone
	// opens System Settings through the opener. Folder commands are the folder
	// adapter's, and Epicenter's own commands go through its generated
	// bindings (below).
	expect(
		importers((specifier) => specifier.startsWith('@tauri-apps/')),
	).toEqual([
		'lib/workspace/desktop-connections.ts imports @tauri-apps/api/core',
		'lib/workspace/desktop-microphone.ts imports @tauri-apps/plugin-opener',
		'lib/workspace/desktop.ts imports @tauri-apps/api/core',
	]);
});

test('a folder is opened only by the two workspaces, each through its own entry', () => {
	// Every other file names the contract, which opens nothing.
	expect(
		importers((specifier) => specifier === '@epicenter/folder/browser'),
	).toEqual(['lib/workspace/browser.ts imports @epicenter/folder/browser']);
	expect(
		importers((specifier) => specifier === '@epicenter/folder/tauri'),
	).toEqual(['lib/workspace/desktop.ts imports @epicenter/folder/tauri']);
	expect(callers('openFolder')).toEqual([
		'lib/workspace/browser.ts',
		'lib/workspace/desktop.ts',
	]);
	const folderEntries = importers((specifier) =>
		specifier.startsWith('@epicenter/folder'),
	).map((found) => found.split(' imports ')[1]);
	expect([...new Set(folderEntries)].sort()).toEqual([
		'@epicenter/folder',
		'@epicenter/folder/browser',
		'@epicenter/folder/file-browser',
		'@epicenter/folder/tauri',
	]);
	// Each build points the exact bare specifier at its workspace's entry
	// (`hostAppViteConfig`); `platform-selection.test.ts` reads what each
	// build pulls in.
});

test('a microphone is reached only through its platform’s recorder entry', () => {
	// In Epicenter Rust owns the microphone (ADR-0571): only the desktop
	// workspace (which also repairs recordings on open) reaches the shell's
	// recorder, and only the WebView microphone reaches the browser's. Shared
	// code names the bare specifier, which is the recording contract alone.
	expect(
		importers((specifier) => specifier === '@epicenter/recorder/tauri'),
	).toEqual([
		'lib/workspace/desktop-microphone.ts imports @epicenter/recorder/tauri',
		'lib/workspace/desktop.ts imports @epicenter/recorder/tauri',
	]);
	expect(
		importers((specifier) => specifier === '@epicenter/recorder/browser'),
	).toEqual(['lib/webview-microphone.ts imports @epicenter/recorder/browser']);
	expect(callers('createWebViewMicrophone')).toEqual([
		'lib/workspace/browser.ts',
	]);
});

test('the build picks the workspace: nothing imports either one but through the seam', () => {
	expect(
		files.filter((file) =>
			/(?:from\s+|import\s*\(\s*)['"][^'"]*workspace\/(desktop|browser)\.js['"]|(?:from\s+|import\s*\(\s*)['"]\.\/(desktop|browser)\.js['"]/.test(
				file.text,
			),
		),
	).toEqual([]);
	expect(importers((specifier) => specifier === '#platform/workspace')).toEqual(
		['lib/workspace/index.ts imports #platform/workspace'],
	);
});

test('the page imports no Yjs store, sync, history, or account module', () => {
	expect(
		importers(
			(specifier) =>
				specifier === 'yjs' ||
				specifier.startsWith('@y/') ||
				specifier.startsWith('@epicenter/sync') ||
				// Rows are edited through the local folder context's cache and
				// drafts (ADR-0528, ADR-0632): no edit session, open-item slot,
				// admission, or save bar. The other shared views are the header
				// status and the failed-save toast.
				(specifier.startsWith('@epicenter/svelte') &&
					![
						'@epicenter/svelte/folder',
						'@epicenter/svelte/write-failure',
						'@epicenter/svelte/write-failure-toast',
						'@epicenter/svelte/status-line',
						'@epicenter/svelte/status-popover',
						'@epicenter/svelte/status-row',
					].includes(specifier)) ||
				specifier.startsWith('@epicenter/auth') ||
				// The store package, by any entry. Folders and their declarations
				// come from `@epicenter/folder` and `@epicenter/definition`.
				specifier === '@epicenter/app' ||
				specifier.startsWith('@epicenter/app/'),
		),
	).toEqual([]);
});

/** Files whose source calls `name(`, ignoring its own declaration. */
function callers(name: string) {
	const call = new RegExp(`(?<!function )\\b${name}\\(`);
	return files.filter((file) => call.test(file.text)).map((file) => file.path);
}

test('the app layout is the only place a session is opened', () => {
	// One folder for the mounted layout, kept across its routes: no page or
	// component opens a workspace or builds product state of its own.
	expect(callers('mountSession')).toEqual(['routes/+layout.svelte']);
	expect(callers('openSession')).toEqual(['lib/session.svelte.ts']);
	expect(callers('createSession')).toEqual(['lib/session.svelte.ts']);
	expect(callers('createLibrary')).toEqual(['lib/session.svelte.ts']);
	// `openSession` takes the opener as a value; nothing else calls it.
	expect(callers('openWorkspace')).toEqual([]);
});

test('every page takes the session from context, and only the shell guards navigation', () => {
	const pages = files.filter((file) => /\+page\.svelte$/.test(file.path));
	expect(pages.map((file) => file.path).sort()).toEqual([
		'routes/+page.svelte',
		'routes/recordings/+page.svelte',
		'routes/transformations/+page.svelte',
	]);
	for (const file of pages) expect(file.text).toContain('getSession()');
	expect(callers('setSession')).toEqual(['routes/components/AppShell.svelte']);
	expect(callers('beforeNavigate')).toEqual([
		'routes/components/AppShell.svelte',
	]);
});

test('only the desktop workspace reaches Epicenter’s commands, through the generated bindings', () => {
	expect(importers((specifier) => specifier.includes('bindings.gen'))).toEqual([
		'lib/workspace/desktop-connections.ts imports ../tauri/bindings.gen.js',
		'lib/workspace/desktop.ts imports ../tauri/bindings.gen.js',
		'lib/workspace/local-transcription.ts imports ../tauri/bindings.gen.js',
	]);
});
