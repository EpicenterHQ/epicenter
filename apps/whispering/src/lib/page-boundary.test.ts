/**
 * What the page may import.
 *
 * The page runs in a WebView and in a browser tab, so nothing under `src/` may
 * reach Node or Bun, or the directory opener that runs there. It names the
 * folder contract through `@epicenter/folder`. A folder is opened in exactly
 * one place: the layout supplies FolderApp its opener. The build selects
 * the browser or desktop Folder entry.
 * The build picks the services (`#platform/services`), so no page code asks
 * where it is running. The recording workflow is
 * file-backed, so it may not reach the Yjs store either. This reads the
 * sources, so a violation names its file.
 *
 * The same reading establishes who owns the folder: the app layout opens one
 * folder context, and pages only receive it.
 */
import { expect, test } from 'bun:test';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = fileURLToPath(new URL('..', import.meta.url));

/** Epicenter's typed command bindings, generated by its build; only the desktop services imports them. */
const GENERATED = 'lib/tauri/bindings.gen.ts';

/** Every page source under `directory`, in name order on every filesystem. */
function* sources(directory: string): Generator<string> {
	for (const name of readdirSync(directory).sort()) {
		const path = join(directory, name);
		if (statSync(path).isDirectory()) yield* sources(path);
		else if (
			/\.(ts|svelte)$/.test(name) &&
			!/\.test(-support)?\.ts$/.test(name)
		)
			yield path;
	}
}

const IMPORT = /(?:from\s+|import\s*\(\s*|import\s+)['"]([^'"]+)['"]/g;

const files = [...sources(src)]
	.map((path) => ({
		path: relative(src, path),
		text: readFileSync(path, 'utf8'),
	}))
	.filter((file) => file.path !== GENERATED);

function importers(matches: (specifier: string) => boolean) {
	const found: string[] = [];
	for (const file of files)
		for (const [, specifier] of file.text.matchAll(IMPORT))
			if (specifier !== undefined && matches(specifier))
				found.push(`${file.path} imports ${specifier}`);
	return found;
}

test('the page imports no Node or Bun module, and Tauri only for a response’s Channel and the opener', () => {
	expect(
		importers(
			(specifier) =>
				specifier.startsWith('node:') ||
				specifier.startsWith('bun') ||
				// The directory opener runs in Bun, never in a page.
				specifier === '@epicenter/folder/bun',
		),
	).toEqual([]);
	// The Tauri APIs the page names: the desktop connections open the
	// `Channel` an AI response streams back on, and the desktop microphone
	// opens System Settings through the opener. Folder commands are the folder
	// adapter's, which opens the folder bound to this window, and Epicenter's
	// own commands go through its generated bindings (below).
	expect(
		importers((specifier) => specifier.startsWith('@tauri-apps/')),
	).toEqual([
		'lib/platform/desktop/connections.ts imports @tauri-apps/api/core',
		'lib/platform/desktop/microphone.ts imports @tauri-apps/plugin-opener',
	]);
});

test('only the layout opens a folder through the build-selected entry', () => {
	expect(
		importers((specifier) =>
			['@epicenter/folder/browser', '@epicenter/folder/tauri'].includes(
				specifier,
			),
		),
	).toEqual([]);
	expect(callers('openFolder')).toEqual(['routes/+layout.svelte']);
});

test('a microphone is reached only through its platform’s recorder entry', () => {
	// In Epicenter Rust owns the microphone (ADR-0571): only the desktop
	// services (which also repairs recordings on open) reaches the shell's
	// recorder, and only the WebView microphone reaches the browser's. Shared
	// code names the bare specifier, which is the recording contract alone.
	expect(
		importers((specifier) => specifier === '@epicenter/recorder/tauri'),
	).toEqual([
		'lib/platform/desktop/microphone.ts imports @epicenter/recorder/tauri',
		'lib/platform/desktop/services.ts imports @epicenter/recorder/tauri',
	]);
	expect(
		importers((specifier) => specifier === '@epicenter/recorder/browser'),
	).toEqual(['lib/webview-microphone.ts imports @epicenter/recorder/browser']);
	expect(callers('createWebViewMicrophone')).toEqual([
		'lib/platform/browser.ts',
	]);
});

test('the build selects browser or desktop services through the seam', () => {
	expect(
		files.filter((file) =>
			/(?:from\s+|import\s*\(\s*)['"][^'"]*platform\/(?:desktop\/services|browser)\.js['"]|(?:from\s+|import\s*\(\s*)['"]\.\/(?:desktop\/services|browser)\.js['"]/.test(
				file.text,
			),
		),
	).toEqual([]);
	expect(importers((specifier) => specifier === '#platform/services')).toEqual([
		'lib/whispering.svelte.ts imports #platform/services',
	]);
});

test('the page imports no Yjs store, sync, history, or account module', () => {
	expect(
		importers(
			(specifier) =>
				specifier === 'yjs' ||
				specifier.startsWith('@y/') ||
				specifier.startsWith('@epicenter/sync') ||
				// Rows are edited through the local folder context's cache and the
				// folder's edit handles (ADR-0528, ADR-0632): no edit whispering,
				// open-item slot, admission, or save bar. The other shared views are
				// the header status and the failed-save toast.
				(specifier.startsWith('@epicenter/svelte') &&
					![
						'@epicenter/svelte/edits',
						'@epicenter/svelte/folder',
						'@epicenter/svelte/folder-app',
						'@epicenter/svelte/folder-queries',
						'@epicenter/svelte/write-failure',
						'@epicenter/svelte/write-failure-toast',
						'@epicenter/svelte/status-line',
						'@epicenter/svelte/status-popover',
						'@epicenter/svelte/status-row',
					].includes(specifier)) ||
				specifier.startsWith('@epicenter/auth') ||
				// The store package, by any entry. Folders and their declarations
				// come from `@epicenter/folder` and `@epicenter/definition`.
				specifier === '@epicenter/app' ||
				specifier.startsWith('@epicenter/app/'),
		),
	).toEqual([]);
});

/** Files whose source calls `name(`, ignoring its own declaration. */
function callers(name: string) {
	const call = new RegExp(`(?<!function )\\b${name}\\(`);
	return files.filter((file) => call.test(file.text)).map((file) => file.path);
}

test('FolderApp owns the folder and WhisperingApp owns product state', () => {
	expect(callers('createWhispering')).toEqual([
		'routes/components/WhisperingApp.svelte',
	]);
	expect(callers('createLibrary')).toEqual(['lib/whispering.svelte.ts']);
	expect(callers('createFolderContext')).toEqual([]);
	expect(callers('createServices')).toEqual(['lib/whispering.svelte.ts']);
	expect(importers((s) => s === '@epicenter/svelte/folder-app')).toEqual([
		'routes/+layout.svelte imports @epicenter/svelte/folder-app',
		'routes/components/test-fixtures/WhisperingRoot.svelte imports @epicenter/svelte/folder-app',
	]);
	expect(callers('setFolder')).toEqual([
		'routes/components/WhisperingApp.svelte',
		'routes/components/test-fixtures/AudioPlaybackHost.svelte',
		'routes/components/test-fixtures/SelectionHost.svelte',
	]);
});

test('every page takes product state from context, and only the app root guards navigation', () => {
	const pages = files.filter((file) => /\+page\.svelte$/.test(file.path));
	expect(pages.map((file) => file.path).sort()).toEqual([
		'routes/+page.svelte',
		'routes/recordings/+page.svelte',
		'routes/transformations/+page.svelte',
	]);
	for (const file of pages) expect(file.text).toContain('getWhispering()');
	expect(callers('setWhispering')).toEqual([
		'routes/components/WhisperingApp.svelte',
		'routes/components/test-fixtures/AudioPlaybackHost.svelte',
		'routes/components/test-fixtures/SelectionHost.svelte',
	]);
	expect(callers('beforeNavigate')).toEqual([
		'routes/components/WhisperingApp.svelte',
	]);
});

test('only the desktop adapter reaches Epicenter’s commands, through the generated bindings', () => {
	expect(importers((specifier) => specifier.includes('bindings.gen'))).toEqual([
		'lib/platform/desktop/connections.ts imports ../../tauri/bindings.gen.js',
		'lib/platform/desktop/services.ts imports ../../tauri/bindings.gen.js',
		'lib/platform/desktop/transcription.ts imports ../../tauri/bindings.gen.js',
	]);
});
