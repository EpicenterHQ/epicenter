#!/bin/sh
# Install the executable. App creation and long-running services are separate commands.
set -eu

fail() { printf '%s\n' "epicenter: $*" >&2; exit 1; }
command -v curl >/dev/null 2>&1 || fail 'curl is required.'
command -v git >/dev/null 2>&1 || fail 'Git is required. Install Git, then run this installer again.'
case "$(uname -s)" in Darwin) os=darwin ;; Linux) os=linux ;; *) fail 'Supported systems: macOS and Linux.' ;; esac
case "$(uname -m)" in arm64|aarch64) arch=arm64 ;; x86_64|amd64) arch=x64 ;; *) fail 'Supported processors: arm64 and x64.' ;; esac
if command -v shasum >/dev/null 2>&1; then
  checksum() { shasum -a 256 < "$1" | awk '{print $1}'; }
elif command -v sha256sum >/dev/null 2>&1; then
  checksum() { sha256sum < "$1" | awk '{print $1}'; }
else
  fail 'shasum or sha256sum is required to verify the download.'
fi

base=${EPICENTER_DOWNLOAD_BASE:-https://github.com/EpicenterHQ/epicenter/releases/download/epicenter-cli-v__EPICENTER_VERSION__}
case "$base" in *__EPICENTER_VERSION__*) fail 'Use the installer generated by bun run --cwd packages/cli release, or set EPICENTER_DOWNLOAD_BASE.' ;; esac
install_dir=${EPICENTER_INSTALL_DIR:-"$HOME/.local/bin"}
case "$install_dir" in /*) ;; *) fail 'EPICENTER_INSTALL_DIR must be an absolute path.' ;; esac
destination=$install_dir/epicenter
if [ -L "$destination" ]; then fail "$destination is a symlink; choose another EPICENTER_INSTALL_DIR."; fi
if [ -e "$destination" ]; then
  existing=$("$destination" --version 2>/dev/null) || fail "$destination is not an Epicenter executable; nothing was replaced."
  case "$existing" in 'epicenter '*) ;; *) fail "$destination is not an Epicenter executable; nothing was replaced." ;; esac
fi
mkdir -p "$install_dir"
download=$(mktemp "$install_dir/.epicenter-download.XXXXXX")
trap 'rm -f "$download" "$download.sha256"' EXIT HUP INT TERM
asset=epicenter-$os-$arch
printf 'Downloading %s\n' "$asset"
curl -fLsS --retry 2 "${base%/}/$asset" -o "$download" || fail "No executable at ${base%/}/$asset. No installed executable was replaced."
curl -fLsS --retry 2 "${base%/}/$asset.sha256" -o "$download.sha256" || fail 'Could not download the checksum; nothing was installed.'
expected=$(tr -d '[:space:]' < "$download.sha256")
case "$expected" in ''|*[!0-9a-f]*) fail 'Invalid download checksum.' ;; esac
[ "${#expected}" -eq 64 ] || fail 'Invalid download checksum.'
[ "$(checksum "$download")" = "$expected" ] || fail 'Checksum mismatch; nothing was installed.'
chmod 755 "$download"
version=$("$download" --version) || fail 'The downloaded executable cannot run on this computer; nothing was installed.'
case "$version" in 'epicenter '*) ;; *) fail 'The download did not identify itself as Epicenter.' ;; esac
mv -f "$download" "$destination"
printf '\nInstalled %s at %s\n' "$version" "$destination"
case ":$PATH:" in *":$install_dir:"*) command_name=epicenter ;; *)
  command_name=$destination
  printf '\nThe install directory is not on PATH. Use the full path below, or add it to your shell configuration.\n'
;; esac
printf '\nNext, with Git user.name and user.email configured:\n'
printf '  "%s" init "$HOME/Epicenter"\n' "$command_name"
printf '  cd "$HOME/Epicenter"\n'
printf "  \"%s\" new writing --from 'https://github.com/EpicenterHQ/epicenter#examples/writing'\n" "$command_name"
printf '  "%s" serve\n' "$command_name"
printf '\nOpen http://127.0.0.1:4747/writing/ while serve runs. MCP: http://127.0.0.1:4747/\n'
