/**
 * Golden vectors for automatic commit subjects.
 *
 * `commitSubject` in `messages.ts` decides the subject a folder writes. Its
 * output is pinned in `fixtures/commit-subjects.txt`, which this script
 * derives, so a change to any subject shows up as a change to that file.
 *
 * Run `bun run gen:vectors` in `packages/folder` to rewrite the fixture, or
 * import `renderVectors` to compare it without writing.
 *
 */
import { commitSubject, type PathChange } from './messages.js';

const add = (path: string): PathChange => ({ path, kind: 'add' });
const modify = (path: string): PathChange => ({ path, kind: 'modify' });
const remove = (path: string): PathChange => ({ path, kind: 'delete' });

/** "Add " plus this many UTF-16 code units is exactly the 72 limit. */
const ADD_ROOM = 72 - 'Add '.length;

const CASES: readonly (readonly PathChange[])[] = [
	[],
	[add('notes/a.md')],
	[modify('notes/a.md')],
	[remove('notes/a.md')],
	[add('a.md'), modify('b.md')],
	[add('a.md'), modify('b.md'), remove('c.md')],
	Array.from({ length: 12 }, (_, index) => modify(`n/${index}.md`)),
	// The limit counts UTF-16 code units, not bytes or code points.
	[add('a'.repeat(ADD_ROOM))],
	[add('a'.repeat(ADD_ROOM + 1))],
	[add('é'.repeat(ADD_ROOM))],
	[add('é'.repeat(ADD_ROOM + 1))],
	[add('日'.repeat(ADD_ROOM))],
	[add('日'.repeat(ADD_ROOM + 1))],
	// An astral character is two code units and four UTF-8 bytes.
	[add('😀'.repeat(ADD_ROOM / 2))],
	[add(`${'😀'.repeat(ADD_ROOM / 2 - 1)}ab`)],
	[add(`${'😀'.repeat(ADD_ROOM / 2)}a`)],
	[modify('é'.repeat(72 - 'Update '.length))],
	[modify('é'.repeat(72 - 'Update '.length + 1))],
	[remove('日'.repeat(72 - 'Delete '.length))],
	[remove('日'.repeat(72 - 'Delete '.length + 1))],
	// Escapes lengthen the subject, and the limit applies after escaping.
	[add('back\\slash.md')],
	[add('tab\there.md')],
	[add('line\nbreak.md')],
	[add('nul\u0000.md')],
	[add('del\u007f.md')],
	[add('c1\u0085\u009f.md')],
	[add('nbsp .md')],
	[add('ls ps .md')],
	[add(`${'a'.repeat(ADD_ROOM - 1)}\\`)],
	[add(`${'a'.repeat(ADD_ROOM - 2)}\\`)],
	[add('naïve/Ünïcödé — notes.md')],
	[add('"quoted".md')],
	[add(' leading and trailing ')],
];

const hex = (text: string) =>
	Array.from(new TextEncoder().encode(text), (byte) =>
		byte.toString(16).padStart(2, '0'),
	).join('');

/** The fixture's exact text. */
export function renderVectors(): string {
	const lines = [
		'# Generated by packages/folder/src/git/commit-subject-vectors.ts from commitSubject in',
		'# packages/folder/src/git/messages.ts. Do not edit by hand.',
		'# <subject as UTF-8 hex, or - for none>\\t<kind:path as UTF-8 hex>,...',
	];
	for (const changes of CASES) {
		const subject = commitSubject(changes);
		lines.push(
			`${subject === undefined ? '-' : hex(subject)}\t${changes
				.map((change) => `${change.kind}:${hex(change.path)}`)
				.join(',')}`,
		);
	}
	return `${lines.join('\n')}\n`;
}

export const VECTORS_PATH = new URL(
	'../../fixtures/commit-subjects.txt',
	import.meta.url,
);

if (import.meta.main) {
	await Bun.write(VECTORS_PATH, renderVectors());
	console.log(`wrote ${CASES.length} cases to ${VECTORS_PATH.pathname}`);
}
